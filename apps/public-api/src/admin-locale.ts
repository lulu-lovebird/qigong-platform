export const adminNameColumn = (locale: AdminLocale): 'name_en' | 'name_zh_tw' =>
  locale === 'en' ? 'name_en' : 'name_zh_tw';
export const adminLocaleQuery = (locale: AdminLocale) => '?lang=' + locale;
export const adminLocaleScript = (locale: AdminLocale) => `
const locale=${JSON.stringify(locale)},t=${JSON.stringify(adminTexts(locale))};
const message=(key,values={})=>t[key].replace(/\\{(\\w+)\\}/g,(_match,name)=>String(values[name] ?? '{'+name+'}'));
const localizedFailure=(error,fallback)=>Object.values(t).includes(error?.message) ? error.message : fallback;
`;
